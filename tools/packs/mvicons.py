"""
Themed world props from the "MV Icons Complete Sheet" (32 x 32 icons, 16 per row): each chosen icon
is halved to the battle's pixel size (each 2 x 2 block becomes its most common color, ties to the
darker; a block is opaque when at least 2 of its pixels are, the same rule as downsample2 in
src/render/pixel/buf.ts), cropped, and written as a one-frame AnimSheet in its own colors with its
feet at the bottom middle.

  python3 -I tools/packs/mvicons.py <MV Icons Complete Sheet Free - ALL.png> <out.ts>
"""
import sys
from PIL import Image

KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&()*+,-/:;<=>?@[]^_{|}~'

# name: (row, column) on the sheet
ICONS = {
    'pumpkin': (148, 8),
    'pumpkinPale': (148, 10),
    'jackOLantern': (148, 12),
    'jackOLanternDim': (148, 11),
    'tombstone': (85, 10),
    'tombstoneFlowers': (85, 12),
    'ghost': (85, 3),
    'blackCat': (85, 1),
    'cauldron': (10, 13),
    'snowman': (129, 14),
    'pineSnowy': (129, 1),
    'xmasTree': (129, 3),
    'presentRed': (129, 8),
    'presentBlue': (129, 9),
    'lollipopRed': (86, 0),
    'lollipopGreen': (86, 2),
    'lollipopSwirl': (10, 1),
    'candyCane': (145, 8),
    'candyCaneGreen': (145, 9),
    'cupcake': (8, 1),
    'cabbage': (148, 0),
    'wheat': (148, 14),
    'spiderWeb': (10, 9),
    'skull': (85, 5),
}


def half(tile):
    out = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    src = tile.load()
    dst = out.load()
    lum = lambda c: c[0] * 0.3 + c[1] * 0.59 + c[2] * 0.11
    for y in range(16):
        for x in range(16):
            cs = [src[x * 2 + dx, y * 2 + dy] for dy in (0, 1) for dx in (0, 1)]
            op = [c for c in cs if c[3] >= 128]
            if len(op) < 2:
                continue
            best = max(op, key=lambda c: (sum(1 for d in op if d[:3] == c[:3]), -lum(c)))
            dst[x, y] = best[:3] + (255,)
    return out


def sheet_ts(name, img):
    bb = img.getbbox()
    img = img.crop(bb)
    w, h = img.size
    px = img.load()
    counts = {}
    for y in range(h):
        for x in range(w):
            if px[x, y][3]:
                counts[px[x, y][:3]] = counts.get(px[x, y][:3], 0) + 1
    pal = sorted(counts, key=lambda c: 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2])
    index = {c: KEYS[i] for i, c in enumerate(pal)}
    rows = [''.join(index[px[x, y][:3]] if px[x, y][3] else '.' for x in range(w)) for y in range(h)]
    bottom = [x for x in range(w) if px[x, h - 1][3]]
    ax = (min(bottom) + max(bottom)) // 2 if bottom else w // 2
    lines = [f'  {name}: {{', f'    w: {w},', f'    h: {h},', f'    anchor: {{ x: {ax}, y: {h - 1} }},', "    faces: 'left',"]
    lines.append('    pal: [' + ', '.join(f"'#{c[0]:02x}{c[1]:02x}{c[2]:02x}'" for c in pal) + '],')
    lines.append('    frames: [[' + ', '.join(f"'{r}'" for r in rows) + ']],')
    lines.append('    anims: { idle: { fps: 1, loop: true, frames: [0] } },')
    lines.append('  },')
    return '\n'.join(lines)


def main():
    src, out = sys.argv[1], sys.argv[2]
    im = Image.open(src).convert('RGBA')
    parts = ['/**', ' * Themed world props from the MV Icons sheet, halved to the battle pixel size (generated by',
             ' * tools/packs/mvicons.py; do not edit). Each is a one-frame sheet with its feet at the bottom middle.', ' */',
             "import type { AnimSheet } from '../indexed';", '', 'export const PROPS = {']
    for name, (r, c) in ICONS.items():
        parts.append(sheet_ts(name, half(im.crop((c * 32, r * 32, c * 32 + 32, r * 32 + 32)))))
    parts.append('} satisfies Record<string, AnimSheet>;')
    parts.append('')
    parts.append('export type PropId = keyof typeof PROPS;')
    open(out, 'w').write('\n'.join(parts) + '\n')
    print(f'wrote {out} ({len(ICONS)} props)')


if __name__ == '__main__':
    main()
