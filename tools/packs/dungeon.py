"""
Exports the 0x72 DungeonTileset II tiles the dungeon battle backdrop uses (src/render/pixel/packs/dungeon.ts)
as indexed rows that share ONE palette (the src/render/pixel/indexed.ts format).

    python3 -I tools/packs/dungeon.py <0x72_DungeonTilesetII_v1.7/frames> src/render/pixel/packs/dungeonTiles.ts

Tiles are copied 1:1 at their full frame size (one source pixel = one art pixel, never scaled or cropped),
so placements keep the pack's 16 px grid; dungeon.ts crops what it needs. The layers are still images,
so animated tiles are single frames, except the fountains: dungeon.ts stacks their three frames into
one long stream. The palette is sorted dark to light. The pack folder is read as data only.
"""
import os
import sys

from PIL import Image

# Must match KEYS in src/render/pixel/indexed.ts.
KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'

TILES = [
    # The back wall: the stone lip along its top, the brick face, banners, holes.
    'wall_top_mid',
    'wall_mid',
    'wall_hole_1',
    'wall_hole_2',
    'wall_banner_red',
    'wall_banner_blue',
    'wall_banner_green',
    'wall_banner_yellow',
    # Gargoyle fountains: heads on the lip, faces and streams (all three frames), basins.
    'wall_fountain_top_2',
    'wall_fountain_top_3',
    'wall_fountain_mid_blue_anim_f0',
    'wall_fountain_mid_blue_anim_f1',
    'wall_fountain_mid_blue_anim_f2',
    'wall_fountain_mid_red_anim_f0',
    'wall_fountain_mid_red_anim_f1',
    'wall_fountain_mid_red_anim_f2',
    'wall_fountain_basin_blue_anim_f0',
    'wall_fountain_basin_red_anim_f0',
    # Engaged columns and the arched door.
    'column',
    'doors_leaf_closed',
    'doors_frame_top',
    'doors_frame_left',
    'doors_frame_right',
    # The floor.
    'floor_1',
    'floor_2',
    'floor_3',
    'floor_4',
    'floor_5',
    'floor_6',
    'floor_7',
    'floor_8',
    # Props.
    'crate',
    'chest_full_open_anim_f0',
    'skull',
]


def lum(c):
    return 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2]


def pixels(im):
    px = im.load()
    return [px[x, y] for y in range(im.height) for x in range(im.width)]


def main():
    if len(sys.argv) != 3:
        raise SystemExit('usage: python3 -I tools/packs/dungeon.py <frames dir> <out.ts>')
    frames_dir, out = sys.argv[1], sys.argv[2]
    images = {}
    for name in TILES:
        path = os.path.join(frames_dir, name + '.png')
        if not os.path.isfile(path):
            raise SystemExit(f'missing tile {path}')
        im = Image.open(path).convert('RGBA')
        if im.width % 16 or im.height % 8:
            raise SystemExit(f'{name}: unexpected size {im.size}')
        partial = sum(1 for p in pixels(im) if 0 < p[3] < 255)
        if partial:
            print(f'warning: {name} has {partial} semi-transparent pixels (alpha >= 128 counts as opaque)', file=sys.stderr)
        images[name] = im

    colors = set()
    for im in images.values():
        colors.update(p[:3] for p in pixels(im) if p[3] >= 128)
    pal = sorted(colors, key=lambda c: (lum(c), c))
    if len(pal) > len(KEYS):
        raise SystemExit(f'{len(pal)} colors, max {len(KEYS)}')
    index = {c: KEYS[i] for i, c in enumerate(pal)}

    lines = [
        '// Generated by tools/packs/dungeon.py from the 0x72 DungeonTileset II v1.7 (frames/). Do not edit by hand.',
        '',
        '/** The tiles\' shared palette: entry k is written as KEYS[k] (src/render/pixel/indexed.ts), dark to light. */',
        'export const DUNGEON_PAL: readonly string[] = [' + ', '.join(f"'#{r:02x}{g:02x}{b:02x}'" for r, g, b in pal) + '];',
        '',
        '/** Pack tiles by their frame name, as indexed rows (\'.\' is transparent), at full frame size. */',
        'export const DUNGEON_TILES: Record<string, readonly string[]> = {',
    ]
    for name in TILES:
        im = images[name]
        px = pixels(im)
        lines.append(f'  {name}: [')
        for y in range(im.height):
            row = ''.join(index[p[:3]] if p[3] >= 128 else '.' for p in px[y * im.width:(y + 1) * im.width])
            lines.append(f"    '{row}',")
        lines.append('  ],')
    lines.append('};')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(TILES)} tiles, {len(pal)} colors -> {out}')


if __name__ == '__main__':
    main()
