"""
Turns character art from the owner's asset packs into AnimSheet modules (src/render/pixel/indexed.ts).

    python3 -I tools/packs/chars.py raccoon <raccoon_sheet.png>              src/render/pixel/packs/raccoon.ts
    python3 -I tools/packs/chars.py fantasy <tiny_rpg_dir> <0x72_frames_dir> src/render/pixel/packs/fantasy.ts
    python3 -I tools/packs/chars.py humans  <mucho_pixels_exported_pngs_dir> src/render/pixel/packs/humans.ts

Art is copied 1:1 (one source pixel = one art pixel, never scaled). Each sheet is cropped to the union
of its frames' opaque pixels and keeps its own palette. Pack folders are read as data only.
"""
import os
import sys

from PIL import Image

KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&()*+,-/:;<=>?@[]^_{|}~'


def rgba(im):
    return im.convert('RGBA')


def opaque(p):
    return p[3] >= 128


def bbox(frames):
    x0 = y0 = 10 ** 9
    x1 = y1 = -1
    for f in frames:
        for y in range(f.height):
            for x in range(f.width):
                if opaque(f.getpixel((x, y))):
                    x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
    return x0, y0, x1 + 1, y1 + 1


def lum(c):
    return 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2]


class Sheet:
    """Collects frames (PIL images, all the same size) and named animations."""

    def __init__(self, name, faces='right'):
        self.name = name
        self.faces = faces
        self.frames = []
        self.anims = {}

    def add(self, anim, images, fps, loop):
        start = len(self.frames)
        self.frames.extend(rgba(i) for i in images)
        self.anims[anim] = (fps, loop, list(range(start, len(self.frames))))

    def alias(self, anim, frames, fps, loop):
        self.anims[anim] = (fps, loop, list(frames))

    def emit(self, export, anchor, crop=True, pad=0, extra=''):
        """`anchor` is in source-frame pixels; returns TS source."""
        w, h = self.frames[0].size
        for f in self.frames:
            assert f.size == (w, h), f'{self.name}: mixed frame sizes'
        x0, y0, x1, y1 = bbox(self.frames) if crop else (0, 0, w, h)
        x0, y0, x1, y1 = max(0, x0 - pad), max(0, y0 - pad), min(w, x1 + pad), min(h, y1 + pad)
        counts = {}
        for f in self.frames:
            for y in range(y0, y1):
                for x in range(x0, x1):
                    p = f.getpixel((x, y))
                    if opaque(p):
                        counts[p[:3]] = counts.get(p[:3], 0) + 1
        pal = sorted(counts, key=lum)
        if len(pal) > len(KEYS):
            raise SystemExit(f'{self.name}: {len(pal)} colors, max {len(KEYS)}')
        index = {c: KEYS[i] for i, c in enumerate(pal)}
        rows_out = []
        for f in self.frames:
            rows = []
            for y in range(y0, y1):
                rows.append(''.join(index[f.getpixel((x, y))[:3]] if opaque(f.getpixel((x, y))) else '.' for x in range(x0, x1)))
            rows_out.append(rows)
        ax, ay = anchor[0] - x0, anchor[1] - y0
        out = [f'export const {export}: AnimSheet = {{']
        out.append(f'  w: {x1 - x0},')
        out.append(f'  h: {y1 - y0},')
        out.append(f'  anchor: {{ x: {ax}, y: {ay} }},')
        out.append(f"  faces: '{self.faces}',")
        out.append('  pal: [' + ', '.join(f"'#{c[0]:02x}{c[1]:02x}{c[2]:02x}'" for c in pal) + '],')
        out.append('  frames: [')
        for rows in rows_out:
            out.append('    [')
            for r in rows:
                out.append(f"      '{r}',")
            out.append('    ],')
        out.append('  ],')
        out.append('  anims: {')
        for name, (fps, loop, frames) in self.anims.items():
            out.append(f"    {name}: {{ fps: {fps}, loop: {'true' if loop else 'false'}, frames: [{', '.join(map(str, frames))}] }},")
        out.append('  },')
        out.append('};')
        self.palette = pal
        return '\n'.join(out) + '\n' + extra


def strip(path, frame_w, frame_h=None):
    im = rgba(Image.open(path))
    frame_h = frame_h or im.height
    return [im.crop((i * frame_w, 0, (i + 1) * frame_w, frame_h)) for i in range(im.width // frame_w)]


def header(src):
    return (
        f'// Generated by tools/packs/chars.py from {src}. Do not edit by hand.\n'
        "import type { AnimSheet } from '../indexed';\n\n"
    )


def palette_indexes(sheet, colors):
    """Palette indexes (after sorting) of the given '#rrggbb' colors, in the order given."""
    pal = ['#%02x%02x%02x' % c for c in sheet.palette]
    return [pal.index(c) for c in colors if c in pal]


def raccoon(src, out):
    im = rgba(Image.open(src))
    cell = 24
    frames = [im.crop((c * cell, r * cell, (c + 1) * cell, (r + 1) * cell)) for r in range(6) for c in range(6)]
    s = Sheet('raccoon')
    s.frames = frames
    s.alias('idle', range(0, 6), 6, True)
    s.alias('look', range(6, 12), 6, True)
    s.alias('cheer', [13, 14, 13, 14], 6, True)
    s.alias('dash', [15], 1, False)
    s.alias('sit', [16], 1, False)
    s.alias('lie', range(18, 24), 9, False)
    s.alias('sleep', range(24, 30), 4, True)
    s.alias('wake', range(30, 36), 9, False)
    body = s.emit('RACCOON', (11, 19), crop=False)
    fur = ['#483429', '#806657', '#b29d8e']
    extra = (
        '\n/** The fur colors (palette indexes, dark to light): recolored for enemy raccoons. */\n'
        f'export const RACCOON_FUR: readonly number[] = [{", ".join(map(str, palette_indexes(s, fur)))}];\n'
    )
    with open(out, 'w') as f:
        f.write(header('art-src/raccoon_sheet.png (Kevin\'s raccoon)') + body + extra)


def fantasy(trpg_dir, x72_dir, out):
    parts = [header('the Tiny RPG Character Asset Pack (Soldier & Orc) and 0x72 DungeonTileset II')]
    names = []
    # The pack's plain Soldier folder still has its drop shadow baked in (one flat color); the game
    # draws its own shadows, so it is removed.
    shadow = {'Soldier': (83, 69, 69), 'Orc': None}
    for who, export in (('Soldier', 'SOLDIER'), ('Orc', 'ORC')):
        d = os.path.join(trpg_dir, who, who)
        s = Sheet(who.lower())

        def load(name):
            frames = strip(os.path.join(d, f'{who}_{name}.png'), 100)
            if shadow[who]:
                for f in frames:
                    px = f.load()
                    for y in range(f.height):
                        for x in range(f.width):
                            if px[x, y][:3] == shadow[who]:
                                px[x, y] = (0, 0, 0, 0)
            return frames

        s.add('idle', load('Idle'), 8, True)
        s.add('walk', load('Walk'), 10, True)
        s.add('attack', load('Attack01'), 14, False)
        s.add('hurt', load('Hurt'), 12, False)
        s.add('death', load('Death'), 9, False)
        idle0 = s.frames[0]
        bx0, by0, bx1, by1 = bbox([idle0])
        parts.append(s.emit(export, ((bx0 + bx1) // 2, by1 - 1)) + '\n')
        names.append((who.lower(), export))
    for name, export in (('pumpkin_dude', 'PUMPKIN'), ('doc', 'DOC'), ('big_demon', 'BIG_DEMON')):
        def frames(kind):
            fs = sorted(f for f in os.listdir(x72_dir) if f.startswith(f'{name}_{kind}_anim_f'))
            return [rgba(Image.open(os.path.join(x72_dir, f))) for f in fs]
        s = Sheet(name)
        s.add('idle', frames('idle'), 6, True)
        s.add('walk', frames('run'), 10, True)
        idle0 = s.frames[0]
        bx0, by0, bx1, by1 = bbox([idle0])
        parts.append(s.emit(export, ((bx0 + bx1) // 2, by1 - 1)) + '\n')
        names.append((name, export))
    with open(out, 'w') as f:
        f.write('\n'.join(parts))


def humans(exported_dir, out):
    d = os.path.join(exported_dir, 'Male', 'Character 1', 'Clothes 3')
    pre = 'Character1M_3_'

    def anim(kind):
        fs = [f for f in os.listdir(d) if f.startswith(pre + kind + '_')]
        fs.sort(key=lambda f: int(f[len(pre + kind) + 1:-4]))
        return [rgba(Image.open(os.path.join(d, f))) for f in fs]

    s = Sheet('officer')
    s.add('idle', anim('idle'), 8, True)
    s.add('walk', anim('walk'), 10, True)
    s.add('attack', anim('punch'), 14, False)
    # The pack's first damage frame is a white silhouette; the game flashes sprites itself.
    s.add('hurt', anim('damage')[1:], 8, False)
    s.add('death', anim('death'), 9, False)
    idle0 = s.frames[0]
    bx0, by0, bx1, by1 = bbox([idle0])
    body = s.emit('OFFICER', ((bx0 + bx1) // 2, by1 - 1))
    # The white shirt, dark to light: recolored to each world's uniform color.
    shirt = [c for c in s.palette if min(c) >= 150 and max(c) - min(c) <= 40]
    extra = (
        '\n/** The shirt colors (palette indexes, dark to light): recolored to each world\'s uniform. */\n'
        f'export const OFFICER_SHIRT: readonly number[] = [{", ".join(str(s.palette.index(c)) for c in shirt)}];\n'
    )
    with open(out, 'w') as f:
        f.write(header('the Mucho Pixels Character Animation Asset Pack (Male, Character 1, Clothes 3)') + body + extra)


if __name__ == '__main__':
    kind = sys.argv[1]
    if kind == 'raccoon':
        raccoon(sys.argv[2], sys.argv[3])
    elif kind == 'fantasy':
        fantasy(sys.argv[2], sys.argv[3], sys.argv[4])
    elif kind == 'humans':
        humans(sys.argv[2], sys.argv[3])
    else:
        raise SystemExit(__doc__)
